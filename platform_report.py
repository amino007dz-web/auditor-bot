def _impact_desc(severity: str, title: str) -> str:
    impacts = {
        "Critical": "Complete loss of funds or contract destruction.",
        "High": "Partial loss of funds or breakage of a core function.",
        "Medium": "Unexpected behavior or limited privilege bypass.",
        "Low": "Violation of best practices or readability issue.",
        "Info": "Additional information with no direct security impact.",
    }
    return impacts.get(severity, "Security impact requiring assessment.")


def prompt_platform():
    print()
    print("Choose a bounty platform:")
    print()
    keys = list(PLATFORMS.keys())
    for i, k in enumerate(keys, 1):
        print(f"  {i}. {PLATFORMS[k]['name']}")
    print()
    try:
        choice = int(input("Platform number: ").strip())
        if 1 <= choice <= len(keys):
            return keys[choice - 1]
    except ValueError:
        pass
    print("⚠️  Invalid choice. Using the general format.")
    return "general"


def main():
    parser = argparse.ArgumentParser(description="Generate platform-specific audit report")
    parser.add_argument("--findings", help="Verified findings file from verify_findings.py")
    parser.add_argument("--platform", choices=list(PLATFORMS.keys()) + ["ask"],
                        default="ask", help="Target platform")
    parser.add_argument("--output", default="", help="Output file")
    args = parser.parse_args()

    # If findings not specified, ask
    findings_path = args.findings
    if not findings_path:
        findings_path = input("Path to findings file (from verify_findings.py): ").strip()
        if not findings_path:
            findings_path = "verified_report.md"

    findings = parse_verified_report(findings_path)
    if not findings:
        print("⚠️  No findings found in the file. Make sure the file contains findings in the format:")
        print('  ### [Critical] Title — `file.sol`')
        print('  **Description:** ...')
        return

    print(f"✓ Found {len(findings)} findings in the file")

    # Platform selection
    platform = args.platform
    if platform == "ask":
        platform = prompt_platform()

    cfg = PLATFORMS.get(platform, PLATFORMS["general"])
    print(f"✓ Platform: {cfg['name']}")

    report = generate_platform_report(findings, platform)

    # Save or print
    output = args.output
    if not output:
        default_name = f"report_{platform}.md"
        output = input(f"Report file name [{default_name}]: ").strip() or default_name

    with open(output, "w", encoding="utf-8") as f:
        f.write(report)

    issues = validate_markdown(report)
    if issues:
        print("⚠️  Validation warnings:")
        for iss in issues:
            print(f"  {iss}")
        print()

    print(f"✓ Report saved: {output}")
    print()
    print(f"Note: {cfg['note']}")
    print()


if __name__ == "__main__":
    main()
