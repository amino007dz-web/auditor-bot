def validate_markdown(text: str) -> List[str]:
    """Validates the report before saving: checks for common Markdown errors."""
    issues = []
    # Unclosed code blocks
    opens = [i for i, line in enumerate(text.split("\n"), 1) if line.strip().startswith("```")]
    if len(opens) % 2 != 0:
        issues.append(f"⚠️  Unclosed code block (starts at line {opens[-1]})")

    # Broken Markdown links [text](url)
    for m in re.finditer(r'\[([^\]]*)\]\(([^)]*)\)', text):
        url = m.group(2).strip()
        if url and not re.match(r'^https?://', url):
            issues.append(f"⚠️  Invalid link: '{m.group(0)}'")

    # Incomplete tables (column count mismatch)
    table_starts = [i for i, line in enumerate(text.split("\n")) if "|" in line and "---" in line]
    for ts in table_starts:
        lines = text.split("\n")
        before = lines[ts - 1].count("|") if ts > 0 else 0
        sep_count = lines[ts].count("|")
        after = lines[ts + 1].count("|") if ts + 1 < len(lines) else 0
        if before != sep_count or after != sep_count:
            issues.append(f"⚠️  Table column mismatch near line {ts + 1}")

    return issues


