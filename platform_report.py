@dataclass
class Finding:
    severity: str
    title: str
    file: str
    description: str
    fix: str = ""
    code: str = ""


def parse_verified_report(path: str) -> List[Finding]:
    """Reads verify_findings.py report and extracts findings"""
    if not os.path.exists(path):
        print(f"file not found: {path}")
        sys.exit(1)

    with open(path, "r", encoding="utf-8") as f:
        text = f.read()

    findings = []
    # Match: ### [Severity] AgentName -- file.ext  then **Description:** ...
    pattern = r"### \[(Critical|High|Medium|Low|Info)\]\s*(.*?)\s*[—–-]+\s*(.+?)\s*\n+\s*\*\*Description:\*\*\s*(.*?)(?=\n###\s|$)"
    for m in re.finditer(pattern, text, re.DOTALL):
        sev = m.group(1)
        title = m.group(2).strip()
        file = m.group(3).strip().strip("`").strip()
        desc = m.group(4).strip()
        fix = ""
        fm = re.search(r"\*\*Recommended Fix:\*\*\s*(.*)", desc)
        if fm:
            fix = fm.group(1).strip()
        findings.append(Finding(sev, title, file, desc, fix))

    return findings


